#!/usr/bin/env node
// PreToolUse guard for Copilot Managed Runtime projects.
// Denies agent edits to codegen output (generated/ and .ms/schemas/) that sits next to an
// ms.config.json, because those files are overwritten by `ms app add/refresh data-source`.
// Set CMR_ALLOW_GENERATED_EDITS=1 to bypass. Fails open: on any error or non-matching input it
// prints nothing and exits 0, so the host's normal permission flow applies (never auto-approves).
import fs from 'node:fs';
import path from 'node:path';

const EDIT_TOOLS = /^(edit|write|multiedit|create|str_replace|str_replace_editor|apply_patch|notebookedit)$/i;

function readStdin(timeoutMs = 2000) {
  return new Promise(resolve => {
    let data = '';
    const t = setTimeout(() => resolve(data), timeoutMs);
    process.stdin.setEncoding('utf8');
    process.stdin.on('data', c => { data += c; });
    process.stdin.on('end', () => { clearTimeout(t); resolve(data); });
    process.stdin.on('error', () => { clearTimeout(t); resolve(data); });
  });
}

function collectPaths(input) {
  const out = [];
  const take = o => {
    if (!o || typeof o !== 'object') return;
    for (const k of ['file_path', 'path', 'filePath', 'notebook_path']) if (typeof o[k] === 'string') out.push(o[k]);
    if (Array.isArray(o.edits)) o.edits.forEach(take);
    if (typeof o.patch === 'string' || typeof o.input === 'string') {
      const text = o.patch ?? o.input;
      for (const m of text.matchAll(/^\*\*\* (?:Update|Add|Delete) File: (.+)$/gm)) out.push(m[1].trim());
    }
  };
  take(input.tool_input);
  let args = input.toolArgs ?? input.tool_args;
  if (typeof args === 'string') { try { args = JSON.parse(args); } catch { args = undefined; } }
  take(args);
  return out;
}

function protectedReason(file, cwd) {
  const abs = path.resolve(cwd, file);
  const parts = abs.split(/[\\/]+/);
  for (let i = parts.length - 2; i >= 0; i--) {
    const isGenerated = parts[i] === 'generated';
    const isSchemas = parts[i] === '.ms' && parts[i + 1] === 'schemas';
    if (!isGenerated && !isSchemas) continue;
    let projectRoot;
    for (let j = i; j > 0 && !projectRoot; j--) {
      const dir = parts.slice(0, j).join(path.sep) || path.sep;
      if (fs.existsSync(path.join(dir.endsWith(':') ? dir + path.sep : dir, 'ms.config.json'))) projectRoot = dir;
    }
    if (projectRoot) {
      return `${path.relative(projectRoot, abs).split(path.sep).join('/')} is Copilot Managed Runtime codegen output (regenerated by \`ms app add/refresh data-source\`). Wrap it in src/data/* instead, or regenerate. Set CMR_ALLOW_GENERATED_EDITS=1 to override.`;
    }
  }
  return undefined;
}

try {
  if (process.env.CMR_ALLOW_GENERATED_EDITS === '1') process.exit(0);
  const raw = (await readStdin()).trim();
  if (!raw) process.exit(0);
  const input = JSON.parse(raw);
  const tool = String(input.tool_name ?? input.toolName ?? '');
  if (!EDIT_TOOLS.test(tool)) process.exit(0);
  const cwd = typeof input.cwd === 'string' ? input.cwd : process.cwd();
  for (const p of collectPaths(input)) {
    const reason = protectedReason(p, cwd);
    if (reason) {
      process.stdout.write(JSON.stringify({
        permissionDecision: 'deny',
        permissionDecisionReason: reason,
        hookSpecificOutput: { hookEventName: 'PreToolUse', permissionDecision: 'deny', permissionDecisionReason: reason },
      }) + '\n');
      process.exit(0);
    }
  }
} catch {
  // fail open
}
process.exit(0);
